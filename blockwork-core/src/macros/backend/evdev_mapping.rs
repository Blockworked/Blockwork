/// Maps a MacroButton to the corresponding evdev Key code for emission.
pub fn macro_button_to_evdev(button: &crate::input::types::MacroButton) -> Option<KeyCode> {
    use crate::input::types::MacroButton;
    Some(match button {
        MacroButton::Left => KeyCode::BTN_LEFT,
        MacroButton::Right => KeyCode::BTN_RIGHT,
        MacroButton::Middle => KeyCode::BTN_MIDDLE,
        MacroButton::Back => KeyCode::BTN_BACK,
        MacroButton::Forward => KeyCode::BTN_FORWARD,
        MacroButton::Other(n) => KeyCode(*n as u16),
        // Scroll variants are emitted as REL_WHEEL, not KEY events
        MacroButton::ScrollUp
        | MacroButton::ScrollDown
        | MacroButton::ScrollLeft
        | MacroButton::ScrollRight => return None,
    })
}

