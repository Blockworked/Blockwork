/// Maps a MacroButton (from a captured mouse button event) to evdev key for re-emission.
pub fn evdev_button_from_code(code: u16) -> Option<crate::input::types::MacroButton> {
    use crate::input::types::MacroButton;
    Some(match KeyCode(code) {
        KeyCode::BTN_LEFT => MacroButton::Left,
        KeyCode::BTN_RIGHT => MacroButton::Right,
        KeyCode::BTN_MIDDLE => MacroButton::Middle,
        KeyCode::BTN_BACK | KeyCode::BTN_SIDE => MacroButton::Back,
        KeyCode::BTN_FORWARD | KeyCode::BTN_EXTRA => MacroButton::Forward,
        _ => return None,
    })
}

